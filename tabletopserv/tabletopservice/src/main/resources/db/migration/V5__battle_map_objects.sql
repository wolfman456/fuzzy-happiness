-- V5 — battle map objects (design-draft-v2 §6, Slice 3b).
--
-- Placed environment items (walls, trees, rocks, ...) on top of the tile grid.
-- Each row is one object instance with an axis-aligned footprint (pos_x, pos_y,
-- width, height). `blocks_movement` marks the footprint as impassable: the
-- server rejects token moves into those squares and the client treats them as
-- walls (path-aware reachability). Tiles and objects are independent layers.
-- Forward-only: never edit V1–V4.

create table if not exists battle_map_objects (
    id bigint generated by default as identity,
    map_id bigint not null,
    object_index integer not null,
    pos_x integer not null,
    pos_y integer not null,
    width integer not null,
    height integer not null,
    rotation integer not null,
    blocks_movement boolean not null,
    primary key (id)
);

alter table if exists battle_map_objects add constraint fk_battle_map_objects_map
    foreign key (map_id) references battle_maps;

create index if not exists idx_battle_map_objects_map on battle_map_objects (map_id);
