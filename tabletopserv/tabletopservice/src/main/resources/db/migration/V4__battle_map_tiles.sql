-- V4 — battle map tiles (design-draft-v2 §6, Slice 3a).
--
-- Adds painted terrain swatches on a per-square grid. A single row per
-- non-empty cell; erasing a square deletes the row. The composite key
-- (map_id, pos_x, pos_y) ensures the grid is single-valued. Tiles are
-- referenced by stable indices from the MapCatalog; never renumber them.
-- Forward-only: never edit V1–V3.

create table if not exists battle_map_tiles (
    tile_index integer not null,
    pos_x integer not null,
    pos_y integer not null,
    id bigint generated by default as identity,
    map_id bigint not null,
    primary key (id),
    unique (map_id, pos_x, pos_y)
);

alter table if exists battle_map_tiles add constraint fk_battle_map_tiles_map
    foreign key (map_id) references battle_maps;
